CREATE TABLE `replenish_order` (
  `ID` varchar(25) NOT NULL,
  `RowID` bigint NOT NULL AUTO_INCREMENT,
  `Keycode` int DEFAULT NULL,
  `ProductID` varchar(13) DEFAULT NULL,
  `SourceLocation` varchar(13) NOT NULL,
  `TargetLocation` varchar(13) NOT NULL,
  `AWS` int DEFAULT NULL,
  `ADS` int DEFAULT NULL,
  `MDU` int DEFAULT NULL,
  `TargetInventory` int DEFAULT NULL,
  `Quantity` int NOT NULL,
  `QuantityFilled` int DEFAULT NULL,
  `SourceInventory` int DEFAULT '0',
  `ClusterWrhInventory` int DEFAULT NULL,
  `Priority` enum('Standard','Fasttrack') NOT NULL DEFAULT 'Standard',
  `DateCreated` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DateDue` datetime NOT NULL,
  `DateFulfilled` datetime DEFAULT NULL,
  `OrderType` enum('Auto','Manual','CrossDock') DEFAULT 'Auto',
  PRIMARY KEY (`RowID`),
  KEY `fk_warehouse_container_idx` (`SourceLocation`),
  KEY `fk_location_container_idx` (`TargetLocation`),
  KEY `idx_Keycode` (`Keycode`),
  KEY `idx_SrcDateRow` (`SourceLocation`,`DateFulfilled`,`RowID`),
  CONSTRAINT `fk_location_container` FOREIGN KEY (`TargetLocation`) REFERENCES `container` (`ID`),
  CONSTRAINT `fk_warehouse_container` FOREIGN KEY (`SourceLocation`) REFERENCES `container` (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
