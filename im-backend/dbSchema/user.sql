CREATE TABLE `user` (
  `ID` int NOT NULL AUTO_INCREMENT,
  `Username` varchar(50) NOT NULL,
  `LoginBarcode` varchar(15) DEFAULT NULL,
  `FirstName` varchar(50) DEFAULT NULL,
  `LastName` varchar(50) DEFAULT NULL,
  `Email` varchar(50) DEFAULT NULL,
  `PhoneNumber` varchar(15) DEFAULT NULL,
  `AccountCreated` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `AccountLastLoggedIn` datetime DEFAULT NULL,
  `PasswordHash` varchar(100) NOT NULL,
  `DefaultLocation` varchar(25) DEFAULT NULL,
  `Locations` varchar(200) DEFAULT NULL,
  `IsDeleted` tinyint NOT NULL DEFAULT '0',
  `googID` varchar(45) DEFAULT NULL,
  `employeeCode` varchar(20) DEFAULT NULL,
  `lastCreated` datetime DEFAULT NULL,
  `lastDeleted` datetime DEFAULT NULL,
  `isSSO` tinyint NOT NULL DEFAULT '0',
  `RegionID` int DEFAULT NULL,
  `is2faRequired` tinyint NOT NULL DEFAULT '0',
  `AuthToken` varchar(32) DEFAULT NULL,
  `DateTokenValid` datetime DEFAULT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `Username` (`Username`),
  UNIQUE KEY `LoginBarcode_UNIQUE` (`LoginBarcode`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
