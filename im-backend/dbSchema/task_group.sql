CREATE TABLE `task_group` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `SourceLocation` varchar(25) NOT NULL,
  `TargetLocation` varchar(25) NOT NULL,
  `DateDue` datetime NOT NULL,
  `Priority` enum('Standard','Fasttrack','Instant','CrossDock') NOT NULL,
  `Type` enum('Pick','Replenish','Inventory','Online','CasePick','Reprice','CrossDock','Backfill','BackfillCount') NOT NULL,
  `CartType` enum('Standard','Apparel','TableLines') DEFAULT NULL,
  `ReferenceID` varchar(25) DEFAULT NULL,
  `DateCreated` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DateCompleted` datetime DEFAULT NULL,
  `DateFulfilled` datetime DEFAULT NULL,
  `isRestricted` tinyint NOT NULL DEFAULT '0',
  `isReserve` tinyint NOT NULL DEFAULT '0',
  `AssignedUserID` int DEFAULT NULL,
  `DateUserAssigned` datetime DEFAULT NULL,
  `Name` varchar(45) DEFAULT NULL,
  `Source` enum('Auto','Manual','Promo') DEFAULT NULL,
  PRIMARY KEY (`ID`),
  KEY `compositeSrc` (`SourceLocation`,`Type`,`DateCompleted`),
  KEY `compositeTgt` (`TargetLocation`,`Type`,`DateFulfilled`),
  KEY `compositeFulfilled` (`Type`,`DateFulfilled`),
  KEY `compositeCompl` (`Type`,`DateCompleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
