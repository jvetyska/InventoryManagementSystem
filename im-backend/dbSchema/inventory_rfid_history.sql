CREATE TABLE `inventory_rfid_history` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `ContainerID` varchar(25) NOT NULL,
  `Keycode` int NOT NULL DEFAULT '0',
  `ProductID` varchar(13) DEFAULT NULL,
  `DateCreated` datetime DEFAULT CURRENT_TIMESTAMP,
  `DateUpdated` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `TagID` varchar(30) DEFAULT NULL,
  `XPosition` float DEFAULT NULL,
  `YPosition` float DEFAULT NULL,
  `ZPosition` float DEFAULT NULL,
  `Certainty` float DEFAULT NULL,
  `MinRSSI` int DEFAULT NULL,
  `MaxRSSI` int DEFAULT NULL,
  `MeanRSSI` float DEFAULT NULL,
  `ReadCount` int DEFAULT NULL,
  `InventoryBotID` int NOT NULL,
  `MapAreaID` varchar(30) NOT NULL,
  `RunName` varchar(45) DEFAULT NULL,
  `IsRemoved` tinyint NOT NULL DEFAULT '0',
  `isSameLocation` tinyint DEFAULT '0',
  PRIMARY KEY (`ID`),
  KEY `idx_Keycode` (`Keycode`),
  KEY `idx_TagID` (`TagID`) /*!80000 INVISIBLE */,
  KEY `idx_bot_map` (`InventoryBotID`,`MapAreaID`,`RunName`),
  KEY `idx_composite` (`ContainerID`,`Keycode`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
