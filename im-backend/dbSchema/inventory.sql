CREATE TABLE `inventory` (
  `ID` bigint NOT NULL AUTO_INCREMENT,
  `ContainerID` varchar(13) NOT NULL,
  `Keycode` int NOT NULL,
  `ProductID` varchar(13) DEFAULT NULL,
  `TaskID` bigint DEFAULT NULL,
  `DateCreated` datetime DEFAULT CURRENT_TIMESTAMP,
  `DateUpdated` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `UserID` int DEFAULT NULL,
  `IsSuspicious` tinyint DEFAULT '0',
  `isSameLocation` tinyint DEFAULT '0',
  `TagID` varchar(30) DEFAULT NULL,
  `XPosition` float DEFAULT NULL,
  `YPosition` float DEFAULT NULL,
  `ZPosition` float DEFAULT NULL,
  `Certainty` float DEFAULT NULL,
  `InventoryBotID` int DEFAULT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `idx_TagID` (`TagID`),
  KEY `idx_Keycode` (`Keycode`),
  KEY `idx_composite` (`ContainerID`,`Keycode`,`TaskID`),
  KEY `idx_task_keycode` (`TaskID`,`Keycode`),
  CONSTRAINT `fk_container_ID` FOREIGN KEY (`ContainerID`) REFERENCES `container` (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
