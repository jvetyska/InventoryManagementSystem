CREATE TABLE `bot_process_history` (
  `ID` int NOT NULL AUTO_INCREMENT,
  `InventoryBotID` int NOT NULL,
  `Name` varchar(45) NOT NULL,
  `Location` varchar(45) DEFAULT NULL,
  `ScanArea` varchar(45) DEFAULT NULL,
  `TaskConfig` varchar(45) DEFAULT NULL,
  `Status` varchar(45) DEFAULT NULL,
  `IsManual` tinyint DEFAULT '0',
  `MapID` int DEFAULT NULL,
  `InventoryTakeScheduleID` bigint DEFAULT NULL,
  `NumTagsRead` int DEFAULT NULL,
  `NumTagsProcessed` int DEFAULT NULL,
  `AverageCertainty` float DEFAULT NULL,
  `RunQualityPct` float DEFAULT NULL,
  `RunDuration` int DEFAULT NULL,
  `isRunAccepted` varchar(45) DEFAULT '0',
  `DateCreated` datetime DEFAULT CURRENT_TIMESTAMP,
  `DateUpdated` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `FailureReason` varchar(45) DEFAULT NULL,
  `FailureReasonType` enum('Auto','Manual') DEFAULT NULL,
  `FailureComment` varchar(1000) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `idx_uniqueComposite` (`InventoryBotID`,`Name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
