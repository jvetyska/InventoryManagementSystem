CREATE TABLE `sale_transaction` (
  `RowID` bigint NOT NULL AUTO_INCREMENT,
  `ID` varchar(50) NOT NULL,
  `Date` datetime NOT NULL,
  `Location` varchar(25) NOT NULL,
  `Keycode` int DEFAULT NULL,
  `ProductID` varchar(25) DEFAULT NULL,
  `GiftCard` varchar(25) DEFAULT NULL,
  `Quantity` int NOT NULL,
  `Price` decimal(11,2) NOT NULL,
  `TaxAmount` decimal(11,2) DEFAULT NULL,
  `DiscountAmount` decimal(11,2) DEFAULT NULL,
  `ShippingAmount` decimal(11,2) DEFAULT NULL,
  `TotalCollected` decimal(11,2) DEFAULT NULL,
  `InventoryOOS` tinyint DEFAULT '0',
  `PickupLocation` varchar(13) DEFAULT NULL,
  `Employee` varchar(100) DEFAULT NULL,
  PRIMARY KEY (`RowID`),
  KEY `ID_idx` (`ID`),
  KEY `idx_Keycode` (`Keycode`) /*!80000 INVISIBLE */,
  KEY `Date_idx` (`Date`,`Location`),
  KEY `sale_transaction_ibfk_1` (`Location`),
  CONSTRAINT `sale_transaction_ibfk_1` FOREIGN KEY (`Location`) REFERENCES `container` (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
