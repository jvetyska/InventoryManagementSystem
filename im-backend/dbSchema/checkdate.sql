CREATE DEFINER=`admin`@`%` FUNCTION `checkdate`(
Timezone VARCHAR(30),
SUN TINYINT(4),
MON TINYINT(4),
TUE TINYINT(4),
WED TINYINT(4),
THU TINYINT(4),
FRI TINYINT(4),
SAT TINYINT(4)
) RETURNS tinyint(1)
BEGIN
	DECLARE WEEKDAY INT;
	DECLARE COVERTEDDATE DATE;
    DECLARE VALID BOOL;
	SET COVERTEDDATE = convert_tz(NOW(), "UTC", Timezone);
	SET WEEKDAY = DAYOFWEEK(COVERTEDDATE);
	SET VALID = FALSE;
    
    IF (WEEKDAY = 1 AND SUN IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;
    IF (WEEKDAY = 2 AND MON IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;
    IF (WEEKDAY = 3 AND TUE IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;
    IF (WEEKDAY = 4 AND WED IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;
    IF (WEEKDAY = 5 AND THU IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;
    IF (WEEKDAY = 6 AND FRI IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;
    IF (WEEKDAY = 7 AND SAT IS TRUE) 
    THEN SET VALID = TRUE;
    END IF;

	RETURN VALID;
END//
DELIMITER ;
