CREATE TABLE `store_inventory_snapshot` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `LocationID` varchar(13) NOT NULL,
  `ContainerID` varchar(13) NOT NULL,
  `BackfillScheduleID` bigint NOT NULL,
  `Keycode` int DEFAULT NULL,
  `Quantity` int DEFAULT NULL,
  `QuantityExternalTotal` int DEFAULT NULL,
  `QuantityExternalStart` int DEFAULT NULL,
  `QuantityExternalEnd` int DEFAULT NULL,
  `QuantityBackfill` int DEFAULT NULL,
  `DateSnapshot` datetime DEFAULT NULL,
  `DateCreated` datetime DEFAULT CURRENT_TIMESTAMP,
  `QuantityCounted` int DEFAULT NULL,
  `QuantityAdjusted` int DEFAULT NULL,
  `AdjustmentReason` varchar(40) DEFAULT NULL,
  `AdjustmentReasonCustom` varchar(500) DEFAULT NULL,
  `DateCounted` datetime DEFAULT NULL,
  `DateCompleted` datetime DEFAULT NULL,
  `DateExternalStart` datetime DEFAULT NULL,
  `DateExternalEnd` datetime DEFAULT NULL,
  `HasRecentManifest` tinyint DEFAULT '0',
  `ExternalInventoryAdjust` tinyint DEFAULT '0',
  `TaskID` bigint DEFAULT NULL,
  `IsOverThreshold` tinyint DEFAULT '0',
  PRIMARY KEY (`ID`),
  KEY `idx_kc_location` (`LocationID`,`Keycode`),
  KEY `idx_backfill_datecompleted` (`BackfillScheduleID`,`DateCompleted`),
  KEY `idx_backfill` (`BackfillScheduleID`,`ContainerID`,`Keycode`,`DateCompleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
