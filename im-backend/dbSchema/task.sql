CREATE TABLE `task` (
  `ID` bigint unsigned NOT NULL AUTO_INCREMENT,
  `TaskGroupID` bigint DEFAULT NULL,
  `Keycode` int DEFAULT NULL,
  `Barcode` varchar(24) DEFAULT NULL,
  `ProductID` varchar(25) DEFAULT NULL,
  `RowID` bigint DEFAULT NULL,
  `Quantity` int NOT NULL,
  `QuantityFilled` int DEFAULT NULL,
  `QuantityDelivered` int DEFAULT NULL,
  `SourceContainer` varchar(25) DEFAULT NULL,
  `TargetContainer` varchar(25) DEFAULT NULL,
  `SecondarySort` varchar(200) DEFAULT NULL,
  `DateCreated` datetime DEFAULT CURRENT_TIMESTAMP,
  `DateCompleted` datetime DEFAULT NULL,
  `DateFulfilled` datetime DEFAULT NULL,
  `DateTransitStart` datetime DEFAULT NULL,
  `DateTransitEnd` datetime DEFAULT NULL,
  `Type` enum('Pick','Replenish','Inventory','Online','CasePick','Reprice','CrossDock','Backfill','BackfillCount') NOT NULL,
  `Priority` enum('Standard','Fasttrack','Instant','CrossDock') DEFAULT NULL,
  `isRestricted` tinyint NOT NULL DEFAULT '0',
  `isSkipped` tinyint NOT NULL DEFAULT '0',
  `isBackup` tinyint NOT NULL DEFAULT '0',
  `isRandom` tinyint NOT NULL DEFAULT '0',
  `ReferenceID` varchar(25) DEFAULT NULL,
  `AssignedUserID` int DEFAULT NULL,
  PRIMARY KEY (`ID`),
  KEY `index_SourceContainer` (`SourceContainer`),
  KEY `idxKeycode` (`Keycode`),
  KEY `referenceID` (`Type`,`ReferenceID`),
  KEY `ROW_ID` (`Type`,`RowID`),
  KEY `userID_idx` (`AssignedUserID`),
  KEY `compositeCompl` (`TaskGroupID`,`DateCompleted`),
  CONSTRAINT `userID` FOREIGN KEY (`AssignedUserID`) REFERENCES `user` (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
